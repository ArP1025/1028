# 练习 1：计算平均分
# 给你一个成绩列表 [85, 92, 78, 90, 88]，用 for 循环把它们加起来，
# 再除以总个数，算出平均分。
# 要求：不能直接用 sum() 函数，自己写循环累加。
# ============================================================
def average_score(scores):
    # 在这里写你的代码
    total = 0
    for score in scores:
        total = total + score

    avg = total / len(scores)
    return avg

# 测试：取消下面这行注释运行
print("练习1 平均分:", average_score([85, 92, 78, 90, 88]))   # 期望: 86.6


