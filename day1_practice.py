# 练习 3：九九乘法表
# 打印九九乘法表，长这样：
# 1x1=1
# 2x1=2  2x2=4
# 3x1=3  3x2=6  3x3=9
# ...
# 9x1=9  ...  9x9=81
# 提示：用两层 for 循环，外层 i 从 1 到 9，内层 j 从 1 到 i。
# ============================================================
def print_multiplication_table():
    for i in range(1,10):
        for j in range(1,i+1):
            print(f"{j}x{i}={i*j}",end=" ")
        print()



# 测试：
print_multiplication_table()


