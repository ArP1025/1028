# 练习 2：判断奇偶
# 写一个函数，输入一个整数，如果是偶数返回 "偶数"，奇数返回 "奇数"。
# 提示：用 % 取余，% 2 == 0 就是偶数。
# ============================================================
def odd_or_even(n):
    if n%2 == 0:
        return('偶数')
    else:
        return('奇数')

# 测试：
print("练习2:", odd_or_even(7))   # 期望: 奇数
print("练习2:", odd_or_even(10))  # 期望: 偶数


